static void bitmap_set_px(uint8_t *bitmap, int w, int h, int x, int y)
{
	int stride;
	int idx;

	if ((x < 0) || (y < 0) || (x >= w) || (y >= h)) {
		return;
	}

	stride = (w + 7) / 8;
	idx = (y * stride) + (x / 8);
	bitmap[idx] |= (uint8_t)(1U << (x & 0x7));
}

static bool bitmap_get_px(const uint8_t *bitmap, int w, int h, int x, int y)
{
	int stride;
	int idx;

	if ((x < 0) || (y < 0) || (x >= w) || (y >= h)) {
		return false;
	}

	stride = (w + 7) / 8;
	idx = (y * stride) + (x / 8);
	return (bitmap[idx] & (uint8_t)(1U << (x & 0x7))) != 0U;
}

static void blit_gfx_bitmap(uint8_t *dst, int dst_w, int dst_h, int x, int y,
			    int src_w, int src_h, const uint8_t *src)
{
	int sx;
	int sy;

	for (sy = 0; sy < src_h; sy++) {
		for (sx = 0; sx < src_w; sx++) {
			if (bitmap_get_px(src, src_w, src_h, sx, sy)) {
				bitmap_set_px(dst, dst_w, dst_h, x + sx, y + sy);
			}
		}
	}
}

